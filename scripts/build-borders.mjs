// Generates src/js/borders.js: simplified outlines of the countries that get
// dedicated weather services (see src/js/regions.js). Source is Natural Earth
// 1:50m (public domain); ~1 km precision is plenty to pick a data provider.
//
//   node scripts/build-borders.mjs [path/to/ne_50m_admin_0_countries.geojson]

import { readFile, writeFile } from 'node:fs/promises';

const SOURCE =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson';
const COUNTRIES = { AUT: 'at', DEU: 'de', CHE: 'ch' };
const TOLERANCE = 0.01; // degrees, ~1 km
const MIN_AREA = 0.01; // square degrees; drops small islands
const OUT = new URL('../src/js/borders.js', import.meta.url);

const geojson = process.argv[2]
  ? JSON.parse(await readFile(process.argv[2], 'utf8'))
  : await (await fetch(SOURCE)).json();

function perpendicular([x, y], [x1, y1], [x2, y2]) {
  const dx = x2 - x1;
  const dy = y2 - y1;
  const len = Math.hypot(dx, dy);
  if (len === 0) return Math.hypot(x - x1, y - y1);
  return Math.abs(dy * x - dx * y + x2 * y1 - y2 * x1) / len;
}

function simplify(points) {
  if (points.length < 3) return points;
  let max = 0;
  let index = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const d = perpendicular(points[i], points[0], points.at(-1));
    if (d > max) {
      max = d;
      index = i;
    }
  }
  if (max <= TOLERANCE) return [points[0], points.at(-1)];
  return [...simplify(points.slice(0, index + 1)).slice(0, -1), ...simplify(points.slice(index))];
}

function area(ring) {
  let sum = 0;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    sum += (ring[j][0] - ring[i][0]) * (ring[j][1] + ring[i][1]);
  }
  return Math.abs(sum / 2);
}

const borders = {};
for (const feature of geojson.features) {
  const id = COUNTRIES[feature.properties.ADM0_A3];
  if (!id) continue;
  const { type, coordinates } = feature.geometry;
  const polygons = type === 'Polygon' ? [coordinates] : coordinates;
  // Outer rings only: none of these countries has an enclave large enough to matter.
  borders[id] = polygons
    .map((polygon) => polygon[0])
    .filter((ring) => area(ring) >= MIN_AREA)
    .map((ring) => simplify(ring).map(([lon, lat]) => [+lat.toFixed(3), +lon.toFixed(3)]));
}

const missing = Object.values(COUNTRIES).filter((id) => !borders[id]);
if (missing.length) throw new Error(`Missing countries in source: ${missing.join(', ')}`);

const body = Object.entries(borders)
  .map(([id, rings]) => `  ${id}: ${JSON.stringify(rings)},`)
  .join('\n');
await writeFile(
  OUT,
  `// Generated by scripts/build-borders.mjs from Natural Earth (public domain). Do not edit.\n` +
    `// Rings of [lat, lon] pairs.\n\nexport const BORDERS = {\n${body}\n};\n`,
);
for (const [id, rings] of Object.entries(borders)) {
  console.info(`${id}: ${rings.length} ring(s), ${rings.reduce((n, r) => n + r.length, 0)} points`);
}
